<?php

declare(strict_types=1);

namespace Modules\AppInstaller\Services\Installer;

/**
 * @internal Extracted from InstallerService (concern group).
 */
trait ConfigLogTrait
{


    /** Config generator — data-driven; `wp` is the WordPress reference writer. */
    private function generateConfig(string $template, array $application, array $v, array $manifest): string
    {
        if ($template === 'wp') {
            $lines = ["<?php\n", "// Generated by cwhpanel Application Installer for {$application['name']}\n"];
            $lines[] = "define('DB_NAME', " . var_export((string)$v['db_name'], true) . ");\n";
            $lines[] = "define('DB_USER', " . var_export((string)$v['db_user'], true) . ");\n";
            $lines[] = "define('DB_PASSWORD', " . var_export((string)$v['db_password'], true) . ");\n";
            $lines[] = "define('DB_HOST', " . var_export((string)$v['db_host'], true) . ");\n";
            $lines[] = "define('DB_CHARSET', 'utf8mb4');\n";
            $lines[] = "define('DB_COLLATE', '');\n";
            foreach (['auth_key','secure_auth_key','logged_in_key','nonce_key','auth_salt','secure_auth_salt','logged_in_salt','nonce_salt'] as $k) {
                $upper = strtoupper($k);
                $lines[] = "define('{$upper}', " . var_export((string)$v[$k], true) . ");\n";
            }
            $lines[] = "\$table_prefix = " . var_export((string)$v['table_prefix'], true) . ";\n";
            $lines[] = "define('WP_DEBUG', false);\n";
            // WordPress only boots (defines wp() et al) when wp-config.php
            // ends with the ABSPATH + wp-settings.php tail — stock
            // wp-config-sample.php carries it, and wp-load.php requires
            // wp-config.php expecting the tail to run. Omitting it leaves
            // every front-end hit fataling on "Call to undefined function
            // wp()" (bitten live on myownhost.ovh).
            $lines[] = "if (!defined('ABSPATH')) { define('ABSPATH', __DIR__ . '/'); }\n";
            $lines[] = "require_once ABSPATH . 'wp-settings.php';\n";
            return implode('', $lines);
        }

        // phpMyAdmin: cookie auth against the local MariaDB; the user logs in
        // with their own DB credentials (no DB user baked into the file).
        if ($template === 'phpmyadmin') {
            $q = static fn (string $s): string => var_export($s, true);
            return "<?php\n"
                . "declare(strict_types=1);\n"
                . "// Generated by cwhpanel Application Installer\n"
                . "\$cfg['blowfish_secret'] = {$q((string)$v['blowfish_secret'])};\n"
                . "\$i = 0;\n"
                . "\$i++;\n"
                . "\$cfg['Servers'][\$i]['auth_type'] = 'cookie';\n"
                . "\$cfg['Servers'][\$i]['host'] = {$q((string)$v['db_host'])};\n"
                . "\$cfg['Servers'][\$i]['compress'] = false;\n"
                . "\$cfg['Servers'][\$i]['AllowNoPassword'] = false;\n"
                . "\$cfg['UploadDir'] = '';\n"
                . "\$cfg['SaveDir'] = '';\n";
        }

        // Roundcube: DB DSN + local IMAP/SMTP; no admin user (mail login).
        if ($template === 'roundcube') {
            $q = static fn (string $s): string => var_export($s, true);
            $dsn = 'mysql://' . rawurlencode((string)$v['db_user']) . ':' . rawurlencode((string)$v['db_password'])
                . '@' . (string)$v['db_host'] . '/' . (string)$v['db_name'];
            return "<?php\n"
                . "// Generated by cwhpanel Application Installer\n"
                . "\$config['db_dsnw'] = {$q($dsn)};\n"
                . "\$config['db_dsnr'] = '';\n"
                . "\$config['des_key'] = {$q((string)$v['des_key'])};\n"
                . "\$config['imap_host'] = 'localhost:143';\n"
                . "\$config['smtp_host'] = 'localhost:587';\n"
                . "\$config['smtp_user'] = '%u';\n"
                . "\$config['smtp_pass'] = '%p';\n"
                . "\$config['default_host'] = 'localhost';\n"
                . "\$config['username_domain'] = '';\n"
                . "\$config['plugins'] = [];\n"
                . "\$config['language'] = 'en_US';\n";
        }

        // OpenCart store/admin config (absolute paths; same values for both).
        if ($template === 'opencart') {
            $q = static fn (string $s): string => var_export($s, true);
            $root = rtrim((string)$v['docroot'], '/') . '/';
            $url = rtrim((string)$v['site_url'], '/') . '/';
            return "<?php\n"
                . "// Generated by cwhpanel Application Installer\n"
                . "define('HTTP_SERVER', {$q($url)});\n"
                . "define('HTTPS_SERVER', {$q($url)});\n"
                . "define('DIR_APPLICATION', {$q($root . 'catalog/')});\n"
                . "define('DIR_SYSTEM', {$q($root . 'system/')});\n"
                . "define('DIR_IMAGE', {$q($root . 'image/')});\n"
                . "define('DIR_STORAGE', {$q($root . 'system/storage/')});\n"
                . "define('DIR_LANGUAGE', DIR_APPLICATION . 'language/');\n"
                . "define('DIR_TEMPLATE', DIR_APPLICATION . 'view/template/');\n"
                . "define('DIR_CONFIG', DIR_SYSTEM . 'config/');\n"
                . "define('DIR_CACHE', DIR_STORAGE . 'cache/');\n"
                . "define('DIR_DOWNLOAD', DIR_STORAGE . 'download/');\n"
                . "define('DIR_LOGS', DIR_STORAGE . 'logs/');\n"
                . "define('DIR_MODIFICATION', DIR_STORAGE . 'modification/');\n"
                . "define('DIR_SESSION', DIR_STORAGE . 'session/');\n"
                . "define('DIR_UPLOAD', DIR_STORAGE . 'upload/');\n"
                . "define('DB_DRIVER', 'mysqli');\n"
                . "define('DB_HOSTNAME', {$q((string)$v['db_host'])});\n"
                . "define('DB_USERNAME', {$q((string)$v['db_user'])});\n"
                . "define('DB_PASSWORD', {$q((string)$v['db_password'])});\n"
                . "define('DB_DATABASE', {$q((string)$v['db_name'])});\n"
                . "define('DB_PORT', '3306');\n"
                . "define('DB_PREFIX', {$q((string)$v['table_prefix'])});\n";
        }

        // OpenCart admin config (paths point at admin/).
        if ($template === 'opencart-admin') {
            $q = static fn (string $s): string => var_export($s, true);
            $root = rtrim((string)$v['docroot'], '/') . '/';
            $url = rtrim((string)$v['site_url'], '/') . '/admin/';
            return "<?php\n"
                . "// Generated by cwhpanel Application Installer\n"
                . "define('HTTP_SERVER', {$q($url)});\n"
                . "define('HTTPS_SERVER', {$q($url)});\n"
                . "define('HTTP_CATALOG', {$q(rtrim((string)$v['site_url'], '/') . '/')});\n"
                . "define('DIR_APPLICATION', {$q($root . 'admin/')});\n"
                . "define('DIR_SYSTEM', {$q($root . 'system/')});\n"
                . "define('DIR_IMAGE', {$q($root . 'image/')});\n"
                . "define('DIR_STORAGE', {$q($root . 'system/storage/')});\n"
                . "define('DIR_LANGUAGE', DIR_APPLICATION . 'language/');\n"
                . "define('DIR_TEMPLATE', DIR_APPLICATION . 'view/template/');\n"
                . "define('DIR_CONFIG', DIR_SYSTEM . 'config/');\n"
                . "define('DIR_CACHE', DIR_STORAGE . 'cache/');\n"
                . "define('DIR_DOWNLOAD', DIR_STORAGE . 'download/');\n"
                . "define('DIR_LOGS', DIR_STORAGE . 'logs/');\n"
                . "define('DIR_MODIFICATION', DIR_STORAGE . 'modification/');\n"
                . "define('DIR_SESSION', DIR_STORAGE . 'session/');\n"
                . "define('DIR_UPLOAD', DIR_STORAGE . 'upload/');\n"
                . "define('DB_DRIVER', 'mysqli');\n"
                . "define('DB_HOSTNAME', {$q((string)$v['db_host'])});\n"
                . "define('DB_USERNAME', {$q((string)$v['db_user'])});\n"
                . "define('DB_PASSWORD', {$q((string)$v['db_password'])});\n"
                . "define('DB_DATABASE', {$q((string)$v['db_name'])});\n"
                . "define('DB_PORT', '3306');\n"
                . "define('DB_PREFIX', {$q((string)$v['table_prefix'])});\n";
        }

        // Joomla configuration.php (the JConfig class the app loads).
        if ($template === 'joomla') {
            $q = static fn ($s): string => var_export((string) $s, true);
            $root = rtrim((string)$v['docroot'], '/');
            $lines = ["<?php\n", "class JConfig {\n"];
            $props = [
                'sitename' => (string)$v['domain'],
                'editor' => 'tinymce',
                'captcha' => '0',
                'list_limit' => '20',
                'access' => '1',
                'frontediting' => '1',
                'dbtype' => 'mysqli',
                'host' => (string)$v['db_host'],
                'user' => (string)$v['db_user'],
                'password' => (string)$v['db_password'],
                'db' => (string)$v['db_name'],
                'dbprefix' => (string)$v['table_prefix'],
                'dbencryption' => '0',
                'secret' => (string)$v['secret'],
                'gzip' => 'false',
                'error_reporting' => 'default',
                'helpurl' => 'https://help.joomla.org/proxy?keyref=Help{major}{minor}:{keyref}&lang={langcode}',
                'tmp_path' => $root . '/tmp',
                'log_path' => $root . '/administrator/logs',
                'live_site' => '',
                'force_ssl' => '0',
                'offset' => 'UTC',
                'lifetime' => '15',
                'session_handler' => 'database',
                'mailonline' => 'true',
                'mailer' => 'mail',
                'mailfrom' => (string)$v['domain'],
                'fromname' => (string)$v['domain'],
                'sendmail' => '/usr/sbin/sendmail',
                'smtpauth' => 'false',
                'smtpuser' => '',
                'smtppass' => '',
                'smtphost' => 'localhost',
                'smtpsecure' => 'none',
                'smtpport' => '25',
                'caching' => '0',
                'cachetime' => '15',
                'cache_handler' => 'file',
                'debug' => 'false',
                'debug_lang' => 'false',
                'debug_lang_const' => 'true',
                'MetaDesc' => '',
                'MetaKeys' => '',
                'MetaTitle' => '1',
                'MetaAuthor' => '1',
                'MetaVersion' => '0',
                'robots' => '',
                'sef' => '1',
                'sef_rewrite' => '0',
                'sef_suffix' => '0',
                'unicodeslugs' => '0',
                'feed_limit' => '10',
                'feed_email' => 'none',
                'cookie_domain' => '',
                'cookie_path' => '',
            ];
            foreach ($props as $k => $val) {
                $lines[] = "\tpublic \$" . $k . ' = ' . $q($val) . ";\n";
            }
            $lines[] = "}\n";
            return implode('', $lines);
        }

        // Serendipity configuration file (db creds + charset).
        if ($template === 'serendipity') {
            $q = static fn ($s): string => var_export((string) $s, true);
            return "<?php\n"
                . "\t/*\n\t  Serendipity configuration file\n\t  Written on " . date('r') . "\n\t*/\n\n"
                . "\t\$serendipity['versionInstalled']  = " . $q((string) $v['app_version']) . ";\n"
                . "\t\$serendipity['dbName']            = " . $q((string) $v['db_name']) . ";\n"
                . "\t\$serendipity['dbPrefix']          = " . $q((string) $v['table_prefix']) . ";\n"
                . "\t\$serendipity['dbHost']            = " . $q((string) $v['db_host']) . ";\n"
                . "\t\$serendipity['dbUser']            = " . $q((string) $v['db_user']) . ";\n"
                . "\t\$serendipity['dbPass']            = " . $q((string) $v['db_password']) . ";\n"
                . "\t\$serendipity['dbType']            = 'mysqli';\n"
                . "\t\$serendipity['dbPersistent']      = false;\n"
                . "\t\$serendipity['dbCharset']         = 'utf8mb4';\n\n"
                . "\t// End of Serendipity configuration file\n"
                . "\t// You can place your own special variables here; see\n"
                . "\t// <https://docs.s9y.org/docs/developers/code-primer.html>\n"
                . "\t// for a list. All defaults from serendipity_config.inc.php\n"
                . "\t// can be changed by re-setting the variables after here:\n?>\n";
        }

        // Homer static dashboard (assets/config.yml).
        if ($template === 'homer') {
            $title = (string) ($v['domain'] !== '' ? $v['domain'] : 'Dashboard');
            return "# Generated by cwhpanel Application Installer\n"
                . "title: \"" . str_replace('"', '', $title) . "\"\n"
                . "subtitle: \"Dashboard\"\n"
                . "logo: \"assets/logo.svg\"\n"
                . "header: true\n"
                . "footer: false\n"
                . "columns: \"auto\"\n"
                . "connectivityCheck: true\n"
                . "defaults:\n  layout: list\n  colorTheme: auto\n"
                . "services: []\n";
        }

        // Generic PHP config template.
        $lines = ["<?php\n", "// Generated by cwhpanel for {$application['name']}\n"];
        foreach ($v as $k => $val) {
            $lines[] = "define(" . var_export(strtoupper($k), true) . ", " . var_export((string)$val, true) . ");\n";
        }
        return implode('', $lines);
    }


    /**
     * Strip secrets before persisting install metadata. The transient
     * `setup` bundle (job payload only) must never land in the row: it
     * carries the plaintext admin password, which JobRunner scrubs from
     * the job once the install settles.
     */
    private function safeConfig(array $opts): array
    {
        $out = $opts;
        unset($out['db_password'], $out['admin_password'], $out['wp'], $out['setup']);
        return $out;
    }


    public function log(int $installationId, string $level, string $message): void
    {
        app('db')->insert('ai_install_logs', [
            'installation_id' => $installationId,
            'level' => $level,
            'message' => mb_substr($message, 0, 2000),
            'created_at' => date('Y-m-d H:i:s'),
        ]);
    }
}

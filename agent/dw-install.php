#!/usr/bin/php
<?php
/**
 * cwhpanel DokuWiki unattended installer helper.
 *
 * Runs as the hosting account user (via runuser from the privileged agent):
 *   php dw-install.php /home/<user>[/<subdir>]
 *
 * Data travels via environment (no shell interpolation anywhere):
 *   DW_TITLE  wiki title (1-200 chars, no NUL/newlines)
 *   DW_USER   admin username, lowercased ([a-z0-9_.-], 1-32)
 *   DW_PASS   admin password (8-256 chars, no NUL/newlines)
 *   DW_EMAIL  admin email (valid address, <=254, no colon)
 *   DW_NAME   admin full name (1-100 chars, no colon/NUL/newlines)
 *
 * Replicates install.php's store_data() for a closed wiki (policy 2):
 *   conf/local.php (title/lang/license/useacl/superuser/register-off),
 *   conf/users.auth.php (bcrypt via native password_hash — DokuWiki's
 *   PassHash verifies $2y$ natively), conf/acl.auth.php (closed),
 *   conf/plugins.local.php (remote auth backends off), then removes
 *   install.php like the wizard instructs.
 *
 * Idempotent: a tree that already has local.php + a real user row prints
 * ALREADY and exits 0 without touching anything.
 *
 * Exit codes: 0 ok (INSTALLED or ALREADY), 1 usage/validation, 2 failure.
 */

declare(strict_types=1);

function fail(int $code, string $msg): never
{
    fwrite(STDERR, $msg . "\n");
    exit($code);
}

$dest = $argv[1] ?? '';
if ($dest === '' || str_contains($dest, "\0") || str_contains($dest, "\n")) {
    fail(1, 'missing install path');
}
$dest = rtrim($dest, '/');
if (!is_dir($dest)) {
    fail(1, "install path is not a directory: {$dest}");
}
foreach (['doku.php', 'inc/init.php', 'conf/dokuwiki.php'] as $probe) {
    if (!is_file($dest . '/' . $probe)) {
        fail(1, "not a DokuWiki tree ({$probe} missing)");
    }
}
if (!is_dir($dest . '/conf') || !is_writable($dest . '/conf')) {
    fail(1, 'conf/ directory missing or not writable');
}

$title = trim((string) (getenv('DW_TITLE') ?: ''));
$user = strtolower(trim((string) (getenv('DW_USER') ?: '')));
$pass = (string) (getenv('DW_PASS') ?: '');
$email = trim((string) (getenv('DW_EMAIL') ?: ''));
$name = trim((string) (getenv('DW_NAME') ?: ''));

if ($title === '' || strlen($title) > 200
    || str_contains($title, "\0") || str_contains($title, "\n") || str_contains($title, "\r")
) {
    fail(1, 'invalid wiki title');
}
if (preg_match('/^[a-z0-9_.-]{1,32}$/', $user) !== 1) {
    fail(1, 'invalid admin username');
}
if (strlen($pass) < 8 || strlen($pass) > 256
    || str_contains($pass, "\0") || str_contains($pass, "\n") || str_contains($pass, "\r")
) {
    fail(1, 'invalid admin password (need 8-256 chars)');
}
if (strlen($email) > 254 || str_contains($email, ':')
    || filter_var($email, FILTER_VALIDATE_EMAIL) === false
) {
    fail(1, 'invalid admin email');
}
if ($name === '') {
    $name = $user;
}
if (strlen($name) > 100 || str_contains($name, ':')
    || str_contains($name, "\0") || str_contains($name, "\n") || str_contains($name, "\r")
) {
    fail(1, 'invalid admin full name');
}

// Already set up? local.php plus at least one real user row.
$localPhp = $dest . '/conf/local.php';
$usersPhp = $dest . '/conf/users.auth.php';
if (is_file($localPhp) && is_file($usersPhp)) {
    $hasUser = false;
    foreach (file($usersPhp, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [] as $line) {
        $line = trim($line);
        if ($line === '' || str_starts_with($line, '#')) {
            continue;
        }
        $hasUser = true;
        break;
    }
    if ($hasUser) {
        echo "ALREADY\n";
        exit(0);
    }
}

$now = date('r');
$write = static function (string $path, string $data): void {
    if (@file_put_contents($path, $data, LOCK_EX) === false) {
        fail(2, "cannot write {$path}");
    }
};

// conf/local.php — mirrors install.php (closed wiki, registration off).
// Single-quote-escape exactly like the installer (addslashes).
$escTitle = addslashes($title);
$write($localPhp, <<<EOT
<?php
/**
 * Dokuwiki's Main Configuration File - Local Settings
 * Auto-generated by cwhpanel Application Installer
 * Date: {$now}
 */
\$conf['title'] = '{$escTitle}';
\$conf['lang'] = 'en';
\$conf['license'] = 'cc-by-sa';
\$conf['useacl'] = 1;
\$conf['superuser'] = '@admin';
\$conf['disableactions'] = 'register';

EOT);

// conf/users.auth.php — bcrypt hash (DokuWiki PassHash verifies $2y$).
$hash = password_hash($pass, PASSWORD_BCRYPT);
$pass = '';
if ($hash === false || !str_starts_with($hash, '$2')) {
    fail(2, 'could not hash admin password');
}
$write($usersPhp, <<<EOT
# users.auth.php
# <?php exit()?>
# Don't modify the lines above
#
# Userfile
#
# Auto-generated by cwhpanel Application Installer
# Date: {$now}
#
# Format:
# login:passwordhash:Real Name:email:groups,comma,separated

{$user}:{$hash}:{$name}:{$email}:admin,user

EOT);

// conf/acl.auth.php — closed wiki (install.php policy 2).
$write($dest . '/conf/acl.auth.php', <<<EOT
# acl.auth.php
# <?php exit()?>
# Don't modify the lines above
#
# Access Control Lists
#
# Auto-generated by cwhpanel Application Installer
# Date: {$now}

*               @ALL          0
*               @user         8

EOT);

// conf/plugins.local.php — remote auth backends off (install.php).
$write($dest . '/conf/plugins.local.php', <<<EOT
<?php
/*
 * Local plugin enable/disable settings
 *
 * Auto-generated by cwhpanel Application Installer
 * Date: {$now}
 */

\$plugins['authad']    = 0;
\$plugins['authldap']  = 0;
\$plugins['authmysql'] = 0;
\$plugins['authpgsql'] = 0;

EOT);

// install.php must go (the wizard says DELETE) — without it DokuWiki keeps
// offering a reinstall to anyone who finds the URL.
if (is_file($dest . '/install.php') && !@unlink($dest . '/install.php')) {
    fail(2, 'setup written but install.php could not be removed (delete it manually)');
}

echo "INSTALLED user={$user}\n";
exit(0);
